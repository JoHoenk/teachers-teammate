"""``INDEX.md``: the one row per run that lets a reader find and check a run file.

The row is computed from what the file itself holds, so the index cannot say more than the run does.
``mean F0.5`` is the mean over the deciding languages, German and English (``—`` when neither has a
score), and ``s/100 words`` is the seconds the model needed per 100 words of student text.  Both
come from :mod:`..report`, so the index and a report of the same export cannot disagree.

The columns between ``Digest`` and ``Test set`` are the axes that vary over the export, printed with
:func:`~..core.axis_table.axis_label`: a reader sees ``temperature 0.4`` and ``steps text-first+review``
and not a column of abbreviations that a new axis would not fit into.

This module must not import :mod:`.export` or the command line.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from ..core import languages
from ..core.axes import date_of, digest8, host_of, varying_axes
from ..core.axis_table import axis_label, axis_values
from ..core.hashing import file_sha256
from ..core.performance import per_100_words
from ..report.groups import DECIDING_LANGUAGES, deciding_mean_f_beta
from ..report.load import ExportedRun, load_export
from ..report.summary import summarise

INDEX_NAME = "INDEX.md"
"""What the list of runs is called, beside the export's own manifest."""

OWN_COLUMNS = frozenset({"model", "model_digest", "testset"})
"""The compare-key names the index prints as their own column, so they are not repeated as axes."""


@dataclass(frozen=True)
class RunSummary:
    """The one row the index shows of a run, computed from what the file itself holds."""

    name: str
    date: str
    machine: str
    model: str
    digest: str
    axes: tuple[tuple[str, str], ...]
    """The varying axes of the export as ``(name, label)``, in compare-key order."""
    testset: str
    texts: int
    mean_f_beta: float | None
    """Mean F0.5 over German and English, as the report's deciding line; ``None`` if neither."""
    seconds_per_100_words: float | None
    scorer_version: int
    """The scorer the numbers came from; numbers of different scorers are never compared."""
    sha256: str


def summarise_run(run: ExportedRun, axes: Sequence[str] = ()) -> RunSummary:
    """Return the index row of one exported run.

    The mean F-beta and the seconds per 100 words are computed from the placed items, as a report
    computes them, so the index and the report cannot disagree.

    Args:
        run: The exported run.
        axes: The axis names to print as columns, as :func:`~..core.axes.varying_axes` returns them
            for the whole export; the row prints its own value of each.
    """
    header = run.header
    items = run.items
    words = sum(item.words for item in items)
    values = axis_values(header.protocol)
    return RunSummary(
        name=run.name,
        date=date_of(run.run.sessions[0].date) if run.run.sessions else "",
        machine=host_of(header),
        model=header.protocol.model,
        digest=digest8(header.protocol.model_digest),
        axes=tuple((name, axis_label(name, values[name])) for name in axes),
        testset=header.input.testset,
        texts=len(items),
        mean_f_beta=deciding_mean_f_beta(summarise(items)),
        seconds_per_100_words=(
            per_100_words(sum(item.seconds for item in items), words) if words else None
        ),
        scorer_version=run.run.scorer_version,
        sha256=file_sha256(run.path),
    )


def summaries(root: Path) -> list[RunSummary]:
    """Return the index row of every run of the export at *root*, in path order.

    The axis columns are the ones that vary over the whole export, so a single run has none and a
    sweep of temperatures has one.
    """
    runs = load_export(root).runs
    axes = [name for name in varying_axes([run.header for run in runs]) if name not in OWN_COLUMNS]
    return [summarise_run(run, axes) for run in runs]


def _and(names: Sequence[str]) -> str:
    """Return *names* as a list a sentence reads: ``A``, ``A and B``, ``A, B and C``."""
    if len(names) <= 1:
        return "".join(names)
    return f"{', '.join(names[:-1])} and {names[-1]}"


def _mean_sentence() -> str:
    """Return the sentence that says which languages the mean covers, from the one table."""
    deciding = [languages.name(code) for code in DECIDING_LANGUAGES]
    reported = [
        languages.name(code) for code in languages.LANGUAGE_NAMES if code not in DECIDING_LANGUAGES
    ]
    sentence = f"`mean F0.5` is the mean over {_and(deciding)}"
    if reported:
        sentence += f"; {_and(reported)} is reported, not averaged"
    return sentence + "."


def _preamble() -> str:
    """Return the text above the table: what the columns mean and what a reader may not edit."""
    return f"""\
# Proofreading runs

Generated by `publish index`; do not edit, and do not add a run by hand.  A run file is written
once by `publish export` and never changed afterwards; this list is the way to
find one, and its last column lets a reader check that the file is still the one that was written.

{_mean_sentence()}  `s/100 words` is the seconds the model needed per 100 words of student text.
A column between `Digest` and `Test set` is an axis the runs of this export differ in, printed the
way a report names it.  `scorer` is the version of the scorer that computed the numbers
(`tools/evaluation/report/score.py`): numbers of different scorers are never compared, and the
commit in the header is information only."""


def _row(row: RunSummary) -> list[str]:
    """Return the cells of one row, in the order :func:`_columns` names them."""
    return [
        row.name,
        row.date,
        row.machine,
        row.model,
        row.digest,
        *(label for _, label in row.axes),
        row.testset,
        str(row.texts),
        "—" if row.mean_f_beta is None else f"{row.mean_f_beta:.3f}",
        "—" if row.seconds_per_100_words is None else f"{row.seconds_per_100_words:.1f}",
        str(row.scorer_version),
        f"`{row.sha256}`",
    ]


def _columns(row: RunSummary) -> list[str]:
    """Return the table's column names for a row of the export."""
    return [
        "Run",
        "Date",
        "Machine",
        "Model",
        "Digest",
        *(name for name, _ in row.axes),
        "Test set",
        "Texts",
        "Mean F0.5",
        "s/100 words",
        "Scorer",
        "SHA-256",
    ]


def index_markdown(root: Path) -> str:
    """Return the contents of ``INDEX.md`` for the runs of the export at *root*."""
    rows = summaries(root)
    lines = [_preamble(), ""]
    if not rows:
        lines.append("No runs yet.")
        return "\n".join(lines) + "\n"
    columns = _columns(rows[0])
    lines.append("| " + " | ".join(columns) + " |")
    lines.append("| " + " | ".join("---" for _ in columns) + " |")
    for row in rows:
        lines.append("| " + " | ".join(_row(row)) + " |")
    return "\n".join(lines) + "\n"


def write_index(root: Path) -> Path:
    """Write ``INDEX.md`` below *root* and return its path."""
    target = root / INDEX_NAME
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(index_markdown(root), encoding="utf-8")
    return target


